/**
 * Builds app/tokens.css from design/tokens.json and checks colour contrast.
 *
 *   node scripts/build-tokens.mjs          write app/tokens.css
 *   node scripts/build-tokens.mjs --check  fail if app/tokens.css is stale (used by `npm run build`)
 *
 * Exits non-zero when a contrast pair in tokens.contrastChecks is below its minimum,
 * so an inaccessible colour change cannot ship.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const SOURCE = `${root}design/tokens.json`;
const OUTPUT = `${root}app/tokens.css`;

const tokens = JSON.parse(readFileSync(SOURCE, "utf8"));
const isMeta = (key) => key.startsWith("$");

// "{color.brand.600}" -> "#d02c75"
function resolve(value) {
  const ref = /^\{(.+)\}$/.exec(value);
  if (!ref) return value;
  const node = ref[1].split(".").reduce((n, k) => n?.[k], tokens);
  if (!node || node.$value === undefined) throw new Error(`Unknown token reference ${value}`);
  return resolve(node.$value);
}

const lines = [];
const emit = (name, value, comment) => lines.push(`  --${name}: ${value};${comment ? ` /* ${comment} */` : ""}`);

for (const [group, scale] of Object.entries(tokens.color)) {
  if (isMeta(group)) continue;
  if (scale.$value) emit(`color-${group}`, scale.$value);
  else for (const [step, t] of Object.entries(scale)) if (!isMeta(step)) emit(`color-${group}-${step}`, t.$value);
}
lines.push("");
for (const [role, t] of Object.entries(tokens.role)) {
  if (!isMeta(role)) emit(`color-${role}`, resolve(t.$value), t.$value.replace(/[{}]/g, "").replace(/^color\./, ""));
}
lines.push("");
for (const [size, t] of Object.entries(tokens.radius)) if (!isMeta(size)) emit(`radius-${size}`, t.$value);
for (const [name, t] of Object.entries(tokens.shadow)) if (!isMeta(name)) emit(`shadow-${name}`, t.$value);

const css = `/* Generated by scripts/build-tokens.mjs from design/tokens.json. Do not edit by hand. */

@theme {
  /* Only Clerikaa colours exist: Tailwind's default palette is removed. */
  --color-*: initial;

${lines.join("\n")}
}
`;

// WCAG 2.x relative luminance and contrast ratio.
function luminance(hex) {
  const [r, g, b] = hex.match(/[0-9a-f]{2}/gi).map((h) => {
    const c = parseInt(h, 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

let failures = 0;
for (const [fg, bg, min] of tokens.contrastChecks.pairs) {
  const ratio = contrast(resolve(tokens.role[fg].$value), resolve(tokens.role[bg].$value));
  if (ratio < min) {
    failures++;
    console.error(`✗ ${fg} on ${bg}: ${ratio.toFixed(2)} < ${min}`);
  }
}
if (failures) {
  console.error(`${failures} contrast check(s) failed. Fix design/tokens.json.`);
  process.exit(1);
}

if (process.argv.includes("--check")) {
  const current = readFileSync(OUTPUT, "utf8");
  if (current !== css) {
    console.error("app/tokens.css is out of date. Run `npm run tokens` and commit the result.");
    process.exit(1);
  }
  console.log(`tokens ok: ${tokens.contrastChecks.pairs.length} contrast pairs pass, app/tokens.css up to date`);
} else {
  writeFileSync(OUTPUT, css);
  console.log(`wrote app/tokens.css; ${tokens.contrastChecks.pairs.length} contrast pairs pass`);
}
